/** Human guidance from parser flags only. Viewing this text never approves a row. */
export interface DocumentCoverage {
  complete?: boolean;
  pages?: number;
  processed?: number;
}

export function documentGuidance(warnings: readonly string[], coverage?: DocumentCoverage) {
  const pending = new Set(warnings);
  const notes: string[] = [];
  const take = (codes: string[], text: string) => {
    if (codes.some((code) => pending.has(code))) notes.push(text);
    for (const code of codes) pending.delete(code);
  };
  if (
    !coverage?.complete ||
    (typeof coverage.pages === "number" && (coverage.processed ?? 0) < coverage.pages)
  )
    notes.push(
      "📄 Документ прочитан не полностью или полнота неизвестна. Сверьте все листы и страницы с оригиналом: в списке могут отсутствовать товары. Пропущенные товары добавьте через «Исправить таблицу».",
    );
  take(
    ["HIDDEN_SHEET"],
    "👁 В файле есть скрытый лист. Его строки тоже извлечены. Откройте лист в исходном файле и решите, нужны ли эти товары; ненужные строки пропустите.",
  );
  take(
    ["HIDDEN_ROWS"],
    "👁 В таблице есть скрытые строки. Они не исключены автоматически. Сверьте их с оригиналом и пропустите те, которые не должны попасть в импорт.",
  );
  take(
    ["MERGED_CELLS"],
    "🧩 В таблице есть объединённые ячейки. Сверьте, к какому товару относятся название, артикул и цена. Пустая ячейка не означает повтор значения из предыдущей строки.",
  );
  take(
    ["MERGED_CELLS_REVIEW"],
    "🧩 Проверьте объединения ячеек в оригинале. Сложная таблица может сместить значения между колонками. Сверьте принадлежность каждого значения товару.",
  );
  take(
    ["FORMULA_NOT_EVALUATED"],
    "🧮 Есть формулы. Бот сохранил их текст, но не вычислял результат. Откройте оригинал и внесите проверенное значение через «Исправить поле».",
  );
  take(
    ["FORMATTED_CELL_REVIEW"],
    "🔢 Есть числа с оформлением. В разборе сохранено исходное число: ведущие нули артикула, дата или вид цены могут отличаться от видимого в файле. Сверьте и исправьте вручную.",
  );
  take(
    ["MIXED_PDF_IMAGES_REQUIRE_VISUAL_REVIEW"],
    "🖼 Сверьте каждую страницу PDF, включая рисунки и сканы. Текстовый слой не гарантирует, что распознаны все товары. Проверьте похожие символы в артикулах.",
  );
  take(
    ["TEXT_LAYOUT_REVIEW"],
    "📐 Колонки выделены по пробелам и отступам. Сверьте заголовки и положение цен: расстояние между словами может быть ошибочно принято за границу колонки.",
  );
  take(
    ["UNSTRUCTURED_TEXT", "SKU_AND_PRICE_REQUIRE_REVIEW", "LINES_MAY_NOT_BE_PRODUCTS"],
    "📝 Получен список строк текста. Заголовок, итог и услуга могут оказаться рядом с товарами. Пропустите лишнее; точную модель, артикул и цену внесите по источнику, без догадок.",
  );
  take(
    ["COLUMN_MAPPING_REVIEW"],
    "🏷 Сверьте смысл колонок: артикул, название, закупочная и розничная цена. Проверьте валюту и единицу продажи. Ошибочный заголовок исправьте через «Исправить таблицу».",
  );
  take(
    ["FORMAT_REQUIRES_MANUAL_CONVERSION"],
    "📎 Этот формат не распознан. Скачайте оригинал, сохраните таблицу как XLSX/TSV или документ как PDF и отправьте новый файл.",
  );
  if (pending.size)
    notes.push(
      "⚠️ Есть дополнительные ограничения распознавания. Сверьте оригинал целиком. Если результат непонятен, подготовьте исправленный файл; не подтверждайте сомнительные строки.",
    );
  if (!notes.length)
    notes.push(
      "Особые предупреждения не отмечены. Перед подтверждением всё равно сверяйте артикулы, названия, цены и количество строк с оригиналом.",
    );
  return [
    "🔎 Что проверить в этой таблице",
    ...notes,
    "Предупреждения относятся к исходному разбору и сохраняются после ваших исправлений. Они не указывают точную проблемную ячейку.",
    "Дальше: Скачайте оригинал и откройте строки. «Исправить поле» меняет одно значение; «Исправить таблицу» — заголовок, пропуск или склеенную строку. Если не уверены, оставьте строку непроверенной или пропустите её.",
    "Просмотр памятки ничего не меняет. Решение «Строка проверена» принимаете вы; импорт и публикация автоматически не запускаются.",
  ].join("\n\n");
}
