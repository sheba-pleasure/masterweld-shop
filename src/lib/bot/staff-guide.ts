export function staffHelp(member: StaffMember): { text: string; rows: BtnRows } {
  const rows: BtnRows = [
    [{ text: "🔍 Найти товар и посмотреть цены", callback_data: "fndh" }],
    [{ text: "🧾 Открыть заказы", callback_data: "orders" }],
    [{ text: "✏️ Продолжить начатый ввод", callback_data: "guide:input" }],
    [{ text: "📝 Проверить мои правки", callback_data: "acts:0" }],
    [{ text: "✖️ Отмена ввода", callback_data: "guide:cancel" }],
  ];
  if (can(member, "edit_products"))
    rows.push([{ text: "➕ Добавить товар", callback_data: "product_new" }]);
  rows.push([{ text: "🏠 Главное меню", callback_data: "home" }]);
  return {
    text: [
      "❓ Как работать с ботом",
      "Товар и цены\nНажмите «Найти товар и посмотреть цены». Напишите название или артикул, выберите товар. «Закупочная и розничная цена» покажет обе цены; ничего не изменится.",
      "Наличие\nВ карточке нажмите «Изменить наличие», выберите «В наличии» или «Под заказ». Бот покажет, что изменится. Сохранение — только после вашего подтверждения.",
      "Заказы\nОткройте заказ. «Начать обработку» означает, что вы занялись заказом. «Заказ собран» — что товары готовы к выдаче. Выдавайте статус «выдан» только после передачи покупателю.",
      "Если остановились на полпути\n«Продолжить начатый ввод» покажет текущий вопрос. «Мои правки» покажет предпросмотр или результат сохранения. Не создавайте ту же правку повторно.",
      "Если передумали\n«Отмена ввода» завершает ввод текста. Для отказа от подготовленной правки нажмите «Отмена» под её предпросмотром. Уже сохранённая правка этим не отменяется.",
      "Кнопки ниже ведут прямо к нужному действию. «Главное меню» позволяет вернуться к началу.",
    ].join("\n\n"),
    rows,
  };
}
